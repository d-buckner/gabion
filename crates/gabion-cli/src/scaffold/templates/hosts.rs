pub(crate) const SERVER_MAIN: &str = r#"//! Server host: choose the impls, mount them, serve. Zero business logic here.
//!
//! `mount_on` is generated by `#[service]` on the trait object, so the host names
//! the impl and nothing else: the routes, the subcommand and the MCP tools all
//! come from the contract.

// Hosts are effect homes: reading argv and owning the process is the job.
#![allow(clippy::disallowed_types, clippy::disallowed_methods)]

use gabion::registry::Host;
use std::sync::Arc;
use %NAME%_%FEATURE%_api::%SVC%Service;
use %NAME%_%FEATURE%_core::%SVC%ServiceImpl;

fn host() -> Host {
    let svc: Arc<dyn %SVC%Service + Send + Sync> =
        Arc::new(%SVC%ServiceImpl::new(gabion_native::NativeCaps::new()));
    let mut host = Host::new();
    svc.mount_on(&mut host);
    host
}

#[tokio::main]
#[allow(clippy::unwrap_used)] // host main is bootstrap; the spec bans unwrap in *-core
async fn main() {
    println!("serving: {}", host().exposed().join(", "));
    println!("routes: {}", host().exposed_routes().join(", "));

    if std::env::args().any(|a| a == "--mcp-stdio") {
        match host().mcp() {
            Some(server) => {
                if let Err(e) = gabion_native::mcp_stdio::serve_stdio(server) {
                    eprintln!("mcp stdio: {e}");
                    std::process::exit(1);
                }
            }
            None => eprintln!("build the api crate with `mcp` to serve tools"),
        }
        return;
    }

    let app = gabion_native::host_router(&mut host());
    let addr = "127.0.0.1:3456";
    let listener = tokio::net::TcpListener::bind(addr).await.unwrap();
    println!("listening on http://{addr}");
    axum::serve(listener, app).await.unwrap();
}
"#;

