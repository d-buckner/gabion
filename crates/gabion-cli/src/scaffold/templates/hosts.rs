pub(crate) const NATIVE_MAIN: &str = r#"//! Native host: one binary, the generated CLI, a file store, and the renderer.
//!
//! Hosts are effect homes — reading env, opening a file and owning the process is
//! exactly what a host is for — and `gabion check` audits that this allow stays in
//! a `host-*` crate.

#![allow(clippy::disallowed_types, clippy::disallowed_methods)]

use clap::Command;
use gabion::prelude::Ctx;
use std::sync::Arc;
use %NAME%_%FEATURE%_api::%SVC%Service;
use %NAME%_%FEATURE%_core::%SVC%ServiceImpl;

const STATE: &str = "%NAME%.store.json";

fn main() {
    let path = std::env::var("%NAME%_STORE").unwrap_or_else(|_| STATE.to_string());
    let caps = match gabion_native::FileCaps::new(path) {
        Ok(caps) => caps,
        Err(e) => {
            eprintln!("cannot open store: {e}");
            std::process::exit(1);
        }
    };
    let svc: Arc<dyn %SVC%Service + Send + Sync> = Arc::new(%SVC%ServiceImpl::new(caps));
    let render = %NAME%_%FEATURE%_render::Svc::new(svc.clone());

    let mut cmd = Command::new("%NAME%")
        .subcommand(%NAME%_%FEATURE%_api::__%FEATURE%_cli::%FEATURE%_cli_command())
        .subcommand(Command::new("ui").about("render the list"));
    let matches = cmd.clone().get_matches();
    let ctx = Ctx::anonymous();

    let rt = match tokio::runtime::Runtime::new() {
        Ok(rt) => rt,
        Err(e) => {
            eprintln!("cannot start runtime: {e}");
            std::process::exit(1);
        }
    };

    let result = rt.block_on(async {
        match matches.subcommand() {
            Some(("%FEATURE%", m)) => {
                let mut out = gabion::cli::IoWriter(std::io::stdout());
                %NAME%_%FEATURE%_api::__%FEATURE%_cli::%FEATURE%_cli_dispatch(
                    svc.as_ref(),
                    &ctx,
                    m,
                    &mut out,
                )
                .await
            }
            Some(("ui", _)) => %NAME%_%FEATURE%_render::render_list(&render)
                .await
                .map_err(|e| gabion::cli::CliExit::from_service(&e)),
            _ => {
                cmd.print_help().ok();
                std::process::exit(0);
            }
        }
    });

    match result {
        Ok(out) => println!("{out}"),
        Err(e) => {
            eprintln!("{e}");
            std::process::exit(e.code);
        }
    }
}
"#;

